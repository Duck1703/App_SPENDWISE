// Base URL is property-driven per Human decision Q3 (ARCHITECTURE §14.2):
//   -Pspendwise.api.base.url / gradle.properties  →  $SPENDWISE_API_BASE_URL  →  placeholder default
val apiBaseUrl: String = providers.gradleProperty("spendwise.api.base.url")
    .orElse(providers.environmentVariable("SPENDWISE_API_BASE_URL"))
    .orElse("https://example.invalid/")
    .get()
    .let { url -> if (url.endsWith("/")) url else "$url/" }

// M21: the host the Network Security Config is scoped to comes straight from
// the configured API URL — the cleartext/CA exceptions always follow config
// and can never drift to cover an unrelated destination. No network address
// is committed to source.
val apiBaseHost: String = URI(apiBaseUrl).host
    ?: throw GradleException(
        "spendwise.api.base.url '$apiBaseUrl' has no host — " +
            "set -Pspendwise.api.base.url or \$SPENDWISE_API_BASE_URL.",
    )

/**
 * M21 Level A/B: renders res/xml/network_security_config.xml for ONE variant.
 *
 *   debug   — cleartextTrafficPermitted only for the configured API host
 *             (the private-LAN dev endpoint); every other destination stays
 *             refused by the manifest's usesCleartextTraffic=false. The LAN CA
 *             is also trusted for that host so debug HTTPS works too.
 *   release — cleartext forbidden everywhere; for the configured host the
 *             app trusts system CAs plus the pinned Spendwise LAN private CA
 *             (public cert in res/raw — the private key never enters the repo).
 *
 * Release additionally fails the build if the URL is http or the committed
 * placeholder — an unconfigured release must not compile.
 */
abstract class GenerateNetworkSecurityConfigTask : DefaultTask() {

    @get:Input
    abstract val buildType: Property<String>

    @get:Input
    abstract val host: Property<String>

    @get:Input
    abstract val url: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val type = buildType.get()
        val apiHost = host.get()
        val apiUrl = url.get()
        val https = apiUrl.startsWith("https://")
        val placeholder = apiHost == "example.invalid"
        if (type == "release") {
            check(!placeholder) {
                "release build requires a real spendwise.api.base.url — " +
                    "still set to the $apiUrl placeholder"
            }
            check(https) {
                "release build requires https:// — got '$apiUrl'. Cleartext " +
                    "release URLs are never permitted."
            }
        }
        val cleartext = type == "debug" && !https
        val xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by GenerateNetworkSecurityConfigTask — do not edit.
     Scoped to the configured API host only ($apiHost); nothing else changes. -->
<network-security-config>
    <domain-config cleartextTrafficPermitted="$cleartext">
        <domain includeSubdomains="false">$apiHost</domain>
        <trust-anchors>
            <certificates src="system" />
            <certificates src="@raw/spendwise_lan_ca" />
        </trust-anchors>
    </domain-config>
</network-security-config>
"""
        outputDir.get().asFile.toPath()
            .resolve("xml/network_security_config.xml")
            .also { Files.createDirectories(it.parent) }
            .toFile()
            .writeText(xml)
    }
}

// M21 release signing — identity is Human-owned (Q4): the build consumes it
// from environment variables only, never from committed files. Supplying none
// produces an unsigned release APK (valid for smoke builds); supplying a
// PARTIAL set fails loudly instead of silently shipping unsigned.
val releaseSigning = listOf(
    "SPENDWISE_RELEASE_KEYSTORE_PATH",
    "SPENDWISE_RELEASE_KEY_ALIAS",
    "SPENDWISE_RELEASE_STORE_PASSWORD",
    "SPENDWISE_RELEASE_KEY_PASSWORD",
).associateWith { providers.environmentVariable(it).orNull }
val releaseSigningConfigured = releaseSigning.values.all { it != null }
val releaseSigningPartial = releaseSigning.values.any { it != null } && !releaseSigningConfigured

android {
    namespace = "com.spendwise.android"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.spendwise.android"
        minSdk = 26
        targetSdk = 36
        // M7: V1 surface is complete (S01–S25 shipped M0–M6). Release
        // versioning/signing ownership stays with THE HUMAN per Q4;
        // this is the internal/direct-install V1 build.
        // M21: monotonic policy — -Pspendwise.versionCode/.versionName may
        // bump per installable release without editing the build file;
        // defaults keep the accepted V1 identity.
        versionCode = providers.gradleProperty("spendwise.versionCode")
            .map(String::toInt).orElse(1).get()
        versionName = providers.gradleProperty("spendwise.versionName").orElse("1.0.0").get()

        // Live UI E2E pre-Application guard (V5 A2): on a placeholder-URL
        // build this behaves exactly like the stock runner; on a live-URL
        // build it refuses Application creation unless opt-in + run-id +
        // a valid on-device L0 attestation are present — before any startup
        // session restore can emit traffic. Test config only; no production
        // behavior changes.
        testInstrumentationRunner = "com.spendwise.android.live.LiveUiE2eRunner"

        buildConfigField("String", "SPENDWISE_API_BASE_URL", "\"$apiBaseUrl\"")
    }

    signingConfigs {
        if (releaseSigningConfigured) {
            create("spendwiseRelease") {
                storeFile = file(releaseSigning.getValue("SPENDWISE_RELEASE_KEYSTORE_PATH")!!)
                keyAlias = releaseSigning.getValue("SPENDWISE_RELEASE_KEY_ALIAS")
                storePassword = releaseSigning.getValue("SPENDWISE_RELEASE_STORE_PASSWORD")
                keyPassword = releaseSigning.getValue("SPENDWISE_RELEASE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            // M21: Human-owned signing identity — wired when the SPENDWISE_RELEASE_*
            // env set is complete; absent → unsigned release artifact (documented).
            if (releaseSigningConfigured) {
                signingConfig = signingConfigs.getByName("spendwiseRelease")
            }
        }
    }

    buildFeatures {
        buildConfig = true
        compose = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

// M21: partial signing config is a defect, not a choice — fail configuration
// before any task runs rather than emitting a silently unsigned release.
check(!releaseSigningPartial) {
    "Incomplete release signing env — expected all of SPENDWISE_RELEASE_KEYSTORE_PATH, " +
        "SPENDWISE_RELEASE_KEY_ALIAS, SPENDWISE_RELEASE_STORE_PASSWORD, " +
        "SPENDWISE_RELEASE_KEY_PASSWORD (got a partial set)."
}

androidComponents {
    onVariants(selector().all()) { variant ->
        val genTask = tasks.register<GenerateNetworkSecurityConfigTask>(
            "generate${variant.name.replaceFirstChar { it.uppercase() }}NetworkSecurityConfig",
        ) {
            buildType.set(variant.buildType)
            host.set(apiBaseHost)
            url.set(apiBaseUrl)
            outputDir.set(layout.buildDirectory.dir("generated/spendwise/${variant.name}/res"))
        }
        variant.sources.res?.addGeneratedSourceDirectory(
            genTask,
            GenerateNetworkSecurityConfigTask::outputDir,
        )
    }
}

